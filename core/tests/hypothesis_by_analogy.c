// tests/hypothesis_by_analogy.c
#include "runtime/ops/opcode.h"
#include "knowledge/algorithm_loader.h"

/*
КОГНИТИВНЫЙ АЛГОРИТМ: Hypothesis By Analogy (Гипотеза по Аналогии)

Ситуация: Мы знаем, что Птица летает: [BIRD] -> [CAN] -> [FLY] (Аналог).

Мы видим Летучую Мышь и хотим предположить, что она тоже летает: [BAT] -> [CAN] -> [FLY].

Старый подход: Искать узлы -> Создавать временные ребра -> Если гипотеза неверна, искать их и удалять (очень медленно).

Новый подход (Hyper-Ops):

Открываем "Сон/Мысль" (OP_SPAWN_CTX).

Создаем там гипотезу (OP_DERIVE) с указанием cause_id на [BIRD]->[CAN]->[FLY].

Если гипотеза валидна (высокий Confidence), схлопываем ветку в реальность (OP_MERGE_CTX).
*/
Pipeline* build_hypothesis_by_analogy_pipeline() {
    Pipeline *p = calloc(1, sizeof(Pipeline));

    // Для примера предполагаем, что необходимые ID уже лежат в регистрах:
    // reg[1] = 0 (Base Context / Реальность)
    // reg[2] = ID_PROCESS_CAN
    // reg[3] = ID_BIRD
    // reg[4] = ID_BAT
    // reg[5] = ID_FLY
    static Instruction code[] = {
        // --- ШАГ 1: Создаем изолированную ветку реальности для размышлений ---
        // OP_SPAWN_CTX автоматически переключит ctx->current_context.
        // ID нового контекста запишем в reg[6].
        { OP_SPAWN_CTX, 0, {6} },

        // --- ШАГ 2: Ищем "прецедент" (аналогию) в базовой реальности ---
        // Ищем: [process = CAN], [participant = BIRD] в [context = BASE (reg[1])]
        // Результаты кладем в scratchpad начиная с индекса 10. Количество результатов в reg[7].
        { OP_QUERY, 0, {2, 3, 1, 10, 7} },

        // (Для упрощения предполагаем, что прецедент найден и он первый)
        // Читаем ID атома-прецедента из scratchpad[10] в reg[8]
        // reg[8] теперь содержит ID факта "[BIRD] -> [CAN] -> [FLY]"
        { OP_READ_SP, 0, {8, 10} },

        // --- ШАГ 3: Формируем гипотезу ---
        // Создаем новый атом: process = CAN (reg[2]), arg0 = BAT (reg[4]), arg1 = FLY (reg[5]).
        // ГЛАВНОЕ: cause_id = reg[8]. Это отвечает на вопрос "Почему ты так решил? -> Потому что птица летает".
        // ID новой гипотезы пишем в reg[9].
        // Поскольку мы в новом контексте (ctx->current_context), этот бред не попадет в основную память.
        { OP_DERIVE, 0, {2, 4, 5, 0, 8, 9} },

        // --- ШАГ 4: "Оценка гипотезы" ---
        // Здесь должны быть инструкции вызова нейросети или логического валидатора,
        // которые найдут этот атом и создадут к нему атом уверенности ID_BELIEF.
        // Для примера загружаем константу порога принятия гипотезы = 0.8f в reg[10]
        { OP_LOAD_CONST, 0, {10, 0x3f4ccccd} }, // float 0.8f (hex)

        // --- ШАГ 5: Схлопывание ---
        // Если гипотеза оправдалась (уверенность > 0.8), переносим успешные атомы
        // из изолированного контекста обратно в базовую реальность.
        // Если провалилась - контекст просто забывается (сборщик мусора почистит LMDB).
        { OP_MERGE_CTX, 0, {10} },

        { OP_HALT, 0, {0} }
    };

    p->code_len = sizeof(code) / sizeof(Instruction);
    p->code = malloc(sizeof(code));
    memcpy(p->code, code, sizeof(code));

    return p;
}
