/* Максимумы */
#define VM_MAX_REGISTERS    64
#define VM_MAX_CALL_DEPTH   32
#define VM_MAX_CYCLES       1000000
#define VM_MAX_OPERATORS    4096
#define VM_EVAL_GRAPH_DEFAULT_STEPS 256   // защита от бесконечного/циклического графа

/*
 * Calling convention: R63 всегда содержит goal_id, для которого была
 * запущена данная асинхронная задача (см. vm_pool.c::vm_worker_txn_fn).
 *
 * Причина существования этой константы: WorkingMemory каждого воркера
 * в vm_pool изолирована (создаётся заново под каждую задачу — это
 * необходимо для потокобезопасности, см. docs/10_VM.md), поэтому
 * OP_WM_TOP_GOAL внутри диспетчеризованного алгоритма НЕ МОЖЕТ повторно
 * найти свою же цель:
 *   (а) WorkingMemory воркера пуста;
 *   (б) даже если бы она не была пуста, OP_WM_TOP_GOAL проверяет
 *       cooldown_until, который OP_DISPATCH_ASYNC уже выставил в
 *       будущее в момент диспетчеризации — то есть алгоритм оказался
 *       бы заблокирован от нахождения именно той цели, ради которой
 *       его запустили.
 *
 * Поэтому goal_id передаётся ЯВНО, как настоящий syscall ABI, а не
 * через повторный обход WorkingMemory / побочное глобальное состояние.
 * Алгоритмам, которым goal_id не нужен (арифметика и т.п.), R63 просто
 * не мешает — они его никогда не читают.
 */
#define VM_REG_GOAL_ID      63
